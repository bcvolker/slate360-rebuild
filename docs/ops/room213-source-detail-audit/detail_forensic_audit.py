def lapvar(a: np.ndarray) -> float:
    a = a.astype(np.float32)
    L = (-4 * a + np.roll(a, 1, 0) + np.roll(a, -1, 0) + np.roll(a, 1, 1) + np.roll(a, -1, 1))[2:-2, 2:-2]
    return float(L.var())


def hf_ratio(a: np.ndarray) -> float:
    f = np.abs(np.fft.fftshift(np.fft.fft2(a.astype(np.float32) - a.mean())))
    h, w = f.shape
    yy, xx = np.mgrid[:h, :w]
    r = np.hypot(yy - h / 2, xx - w / 2) / (min(h, w) / 2)
    tot = f.sum()
    return float(f[r > 0.25].sum() / tot) if tot > 0 else 0.0


def local_contrast(a: np.ndarray) -> float:
    return float(a.astype(np.float32).std())


def michelson(a: np.ndarray) -> float:
    lo, hi = np.percentile(a, [1, 99])
    return float((hi - lo) / (hi + lo)) if (hi + lo) > 0 else 0.0


def esf_width_px(a: np.ndarray) -> float | None:
    """10-90% edge-spread width at the strongest edge in the ROI. Finds the pixel with
    max horizontal gradient magnitude, then measures the transition width along that row."""
    a = a.astype(np.float32)
    if a.shape[0] < 8 or a.shape[1] < 16:
        return None
    gx = np.abs(np.diff(a, axis=1))
    gx[:, :3] = 0
    gx[:, -3:] = 0
    idx = np.unravel_index(np.argmax(gx), gx.shape)
    row, col = idx
    lo = max(0, col - 15)
    hi = min(a.shape[1], col + 16)
    profile = a[row, lo:hi]
    if profile.max() == profile.min():
        return None
    norm = (profile - profile.min()) / (profile.max() - profile.min())
    rising = norm[-1] > norm[0]
    if not rising:
        norm = norm[::-1]
    below = np.where(norm < 0.1)[0]
    above = np.where(norm > 0.9)[0]
    if len(below) == 0 or len(above) == 0:
        return None
    i0 = below[-1] if below[-1] < (above[0] if len(above) else len(norm)) else below.max()
    candidates_below = below[below < above.max()] if len(above) else below
    if len(candidates_below) == 0:
        return None
    i0 = candidates_below.max()
    i1 = above[above > i0]
    if len(i1) == 0:
        return None
    return float(i1.min() - i0)


def blockiness(a: np.ndarray) -> float:
    a = a.astype(np.float32)
    h, w = a.shape
    gx = np.abs(np.diff(a, axis=1))
    cols = np.arange(gx.shape[1])
    on_block = (cols % 8) == 7
    if on_block.sum() == 0 or (~on_block).sum() == 0:
        return float("nan")
    return float(gx[:, on_block].mean() / (gx[:, ~on_block].mean() + 1e-6))


def box_downsample(a: np.ndarray, d: int) -> np.ndarray:
    """Exact equivalent of nerfstudio splatfacto's own resize_image() (splatfacto.py:110-121,
    "Downscale images using the same 'area' method in opencv": a dxd uniform-weight conv2d
    with stride=d) -- this is the LIVE per-step downscale splatfacto's _downscale_if_required()
    actually applies during the progressive-resolution training window, confirmed by reading
    the installed nerfstudio 1.1.5 source directly (not the unrelated PIL-BILINEAR resize in
    base_dataset.py's InputDataset.get_numpy_image, which is a different, unused code path
    here since camera_res_scale_factor=1.0 in every arm of this pipeline)."""
    h, w = a.shape
    h2, w2 = h // d, w // d
    return a[: h2 * d, : w2 * d].reshape(h2, d, w2, d).mean(axis=(1, 3))


def angular_density(cx_roi: float, cy_roi: float) -> float:
    r = math.hypot(cx_roi - 640, cy_roi - 640)
    theta = math.atan(r / FL)
    px_per_rad = FL / (math.cos(theta) ** 2)
    return px_per_rad * math.pi / 180.0


def stage_metrics(gray: np.ndarray, cx: float, cy: float) -> dict:
    return {
        "dims_px": list(gray.shape[::-1]),
        "lapvar": round(lapvar(gray), 2),
        "hf_ratio": round(hf_ratio(gray), 4),
        "local_contrast": round(local_contrast(gray), 2),
        "michelson": round(michelson(gray), 4),
        "esf_width_px": (round(w, 2) if (w := esf_width_px(gray)) is not None else None),
        "blockiness": round(blockiness(gray), 4),
    }


