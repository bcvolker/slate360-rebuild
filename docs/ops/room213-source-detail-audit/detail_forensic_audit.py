def load_gray(path: Path) -> np.ndarray:
    return np.asarray(Image.open(path).convert("L"))


def crop_box(a: np.ndarray, bbox: tuple[int, int, int, int]) -> np.ndarray:
    x0, y0, x1, y1 = bbox
    return a[y0:y1, x0:x1]


def main() -> None:
    results = []
    panel_cache: dict[str, np.ndarray] = {}

    for roi in ROIS:
        gt_path = MIRROR / f"{roi['station']}_v{roi['v'][1:]}.jpg"
        gt_full = load_gray(gt_path)
        bbox = roi["bbox"]
        cx = (bbox[0] + bbox[2]) / 2
        cy = (bbox[1] + bbox[3]) / 2

        gt_roi = crop_box(gt_full, bbox)
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]

        gt640 = box_downsample(gt_full, 2)
        gt320 = box_downsample(gt_full, 4)
        bbox640 = tuple(int(v / 2) for v in bbox)
        bbox320 = tuple(int(v / 4) for v in bbox)
        gt_roi_640 = crop_box(gt640, bbox640)
        gt_roi_320 = crop_box(gt320, bbox320)

        stages = {
            "1280_crop": stage_metrics(gt_roi, cx, cy),
            "640_downsample": stage_metrics(gt_roi_640, cx / 2, cy / 2) if gt_roi_640.size else None,
            "320_downsample": stage_metrics(gt_roi_320, cx / 4, cy / 4) if gt_roi_320.size else None,
        }

        render_stage = None
        if roi["v"] == "v00" and roi["station"] in PANEL_FOR_STATION:
            pname = PANEL_FOR_STATION[roi["station"]]
            if pname not in panel_cache:
                panel_cache[pname] = load_gray(PANELS / f"{pname}.png")
            panel = panel_cache[pname]
            seg_w = panel.shape[1] // 4
            gt_seg = panel[:, :seg_w]
            render_seg = panel[:, seg_w:2 * seg_w]
            # panel segments are ~1280-wide GT-aligned crops; bbox applies directly
            # (clip in case the segment is a few px narrower than 1280)
            bx = (min(bbox[0], seg_w - 1), bbox[1], min(bbox[2], seg_w), bbox[3])
            render_roi = crop_box(render_seg, bx)
            gt_seg_roi = crop_box(gt_seg, bx)
            if render_roi.size and gt_seg_roi.size:
                render_stage = stage_metrics(render_roi, cx, cy)
                render_stage["gt_cross_check_lapvar"] = round(lapvar(gt_seg_roi), 2)
                render_stage["gt_cross_check_matches_mirror"] = abs(
                    lapvar(gt_seg_roi) - stages["1280_crop"]["lapvar"]
                ) < 0.15 * max(1.0, stages["1280_crop"]["lapvar"])

        stages["trained_render_h5"] = render_stage

        results.append({
            "id": roi["id"], "station": roi["station"], "view": roi["v"],
            "direction_class": roi["cls"], "category": roi["category"], "note": roi["note"],
            "bbox_1280": list(bbox), "roi_dims_px": [w, h],
            "angular_px_per_deg_at_center": round(angular_density(cx, cy), 2),
            "stages": stages,
        })

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "roi_results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")

    # console summary
    for r in results:
        s = r["stages"]
        render = s["trained_render_h5"]
        print(
            f"{r['id']} {r['category']:16s} {r['direction_class']:14s} "
            f"1280 lv={s['1280_crop']['lapvar']:8.1f} esf={s['1280_crop']['esf_width_px']} "
            f"640 lv={s['640_downsample']['lapvar']:8.1f} "
            f"320 lv={s['320_downsample']['lapvar']:8.1f} "
            + (f"render lv={render['lapvar']:8.1f} ratio={render['lapvar']/max(1,s['1280_crop']['lapvar']):.2f}" if render else "render n/a")
        )


if __name__ == "__main__":
    main()
